"""att03_endpoints.py — bake the kiosk API endpoint(s) into js/endpoints.js.

The tablet never asks anyone for the API URL or key: this script reads them
from exports/ and writes js/endpoints.js (gitignored), which the app loads and
resolves BY SITE at runtime (Sync.endpointFor(site)). Re-run after rotating the
key or adding a per-site key, then bump the ?v= strings / CACHE and redeploy.

Sources (all under exports/, never committed):
  att02_callback_url.txt + att02_key.txt            -> default (every site)
  att03_<SITE>_url.txt   + att03_<SITE>_key.txt     -> per-site override (optional;
                                                       SITE = code in config.js, e.g. LAUNA)

Usage:  py scripts/att03_endpoints.py [--check]
  --check  only report what would be written (no file change)
"""
import base64
import datetime as dt
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXPORTS = os.path.join(HERE, "exports")
OUT = os.path.join(HERE, "js", "endpoints.js")
CONFIG = os.path.join(HERE, "js", "config.js")


def b64(s):
    return base64.b64encode(s.encode("utf-8")).decode("ascii")


def read(name):
    p = os.path.join(EXPORTS, name)
    if not os.path.exists(p):
        return ""
    with open(p, encoding="utf-8") as f:
        return f.read().strip()


def site_codes():
    with open(CONFIG, encoding="utf-8") as f:
        src = f.read()
    block = src.split("sites: {", 1)[1].split("},\n  defaultSite", 1)[0]
    return re.findall(r"^\s*([A-Z0-9]+):\s*\{", block, re.M)


def main():
    check = "--check" in sys.argv
    url, key = read("att02_callback_url.txt"), read("att02_key.txt")
    if not url or not key:
        sys.exit("exports/att02_callback_url.txt and exports/att02_key.txt are required (att02 --phases u)")
    sites = {}
    for code in site_codes():
        u, k = read(f"att03_{code}_url.txt"), read(f"att03_{code}_key.txt")
        if u or k:
            sites[code] = {"u": b64(u or url), "k": b64(k or key)}
    data = {
        "generated": dt.datetime.now().isoformat(timespec="seconds"),
        "default": {"u": b64(url), "k": b64(key)},
        "sites": sites,
    }
    print(f"default endpoint: {url[:60]}… key {len(key)} chars")
    print(f"per-site overrides: {', '.join(sites) or 'none (all sites use the default)'}")
    if check:
        return
    body = (
        "// GENERATED by scripts/att03_endpoints.py — do not edit by hand; re-run the script instead.\n"
        "const ATT_ENDPOINTS = " + json.dumps(data, indent=2) + ";\n"
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
